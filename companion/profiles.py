"""Strict local action configuration and presentation-only device profiles."""
from __future__ import annotations

import base64
import copy
import json
import re
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit

from .protocol import MAX_MESSAGE, ProtocolError, decode_json, encode_json
from .settings import atomic_json, resource_directory

MAX_PROFILES = 8
MAX_BUTTONS = 24
MAX_LOCAL_PROFILE = 524288
IDENTIFIER = re.compile(r"^[a-z][a-z0-9_-]{0,31}$")
CATEGORIES = ("default", "development", "media", "gaming", "productivity", "custom")
ICONS = {
    "code": "‹›", "terminal": ">_", "powershell": "PS", "folder": "▣",
    "github": "GH", "project": "◇", "server": "▤", "camera": "◎",
    "play": "▶", "next": "▶|", "previous": "|◀", "volume_up": "+",
    "volume_down": "−", "mute": "×", "copy": "▢", "paste": "▣",
    "cut": "✂", "undo": "↶", "save": "↓", "desktop": "▱",
    "lock": "▥", "browser": "○", "text": "Aa", "game": "+",
    "mail": "✉", "calendar": "▦", "search": "⌕", "star": "☆",
    "custom": "◇",
}
ACTION_TYPES = (
    "launch_app", "keyboard_shortcut", "media_play_pause", "media_next",
    "media_previous", "volume_up", "volume_down", "volume_mute", "screenshot",
    "open_url", "lock_windows", "show_desktop", "text_snippet",
)
APP_ALIASES = {"code", "terminal", "powershell", "explorer", "project", "dev_server"}
NAMED_KEYS = {"ctrl", "shift", "alt", "win", "enter", "tab", "space", "escape",
              "backspace", "delete", "insert", "home", "end", "pageup", "pagedown",
              "up", "down", "left", "right", "printscreen", "capslock",
              "plus", "minus", "comma", "period", "slash", "semicolon"}
NAMED_KEYS.update(f"f{i}" for i in range(1, 25))
NAMED_KEYS.update("abcdefghijklmnopqrstuvwxyz0123456789")


def _text(value: Any, name: str, limit: int, empty: bool = False) -> str:
    if not isinstance(value, str) or "\x00" in value or len(value.encode("utf-8")) > limit:
        raise ValueError(f"Invalid {name} (maximum {limit} UTF-8 bytes)")
    if not empty and not value.strip():
        raise ValueError(f"{name} cannot be empty")
    if any(ord(c) < 32 for c in value) and name != "snippet":
        raise ValueError(f"Control characters in {name}")
    return value


def identifier(value: Any, name: str = "ID") -> str:
    if not isinstance(value, str) or not IDENTIFIER.fullmatch(value):
        raise ValueError(f"{name} must start with a–z and use a–z, 0–9, _ or - (32 characters)")
    return value


def validate_shortcut(value: Any) -> list[str]:
    value = _text(value, "shortcut", 80)
    keys = [part.strip().lower() for part in value.split("+")]
    if not 1 <= len(keys) <= 5 or len(set(keys)) != len(keys) or any(k not in NAMED_KEYS for k in keys):
        raise ValueError("Use supported keys separated by +, such as ctrl+shift+s")
    modifiers = {"ctrl", "shift", "alt", "win"}
    if sum(k not in modifiers for k in keys) != 1 or keys[-1] in modifiers:
        raise ValueError("A shortcut requires modifiers followed by one key")
    if set(keys) == {"ctrl", "alt", "delete"}:
        raise ValueError("Windows secure attention (Ctrl+Alt+Delete) cannot be generated by an app")
    return keys


def validate_action(value: Any) -> dict[str, Any]:
    if not isinstance(value, dict) or value.get("type") not in ACTION_TYPES:
        raise ValueError("Unsupported action type")
    kind = value["type"]
    allowed: set[str] = {"type"}
    result: dict[str, Any] = {"type": kind}
    if kind == "launch_app":
        allowed |= {"target", "args", "cwd"}
        target = _text(value.get("target"), "application target", 1024)
        if target not in APP_ALIASES:
            path = Path(target)
            if not path.is_absolute() or path.suffix.lower() != ".exe":
                raise ValueError("Select an absolute .exe path or an approved application alias")
        args = value.get("args", [])
        if not isinstance(args, list) or len(args) > 32:
            raise ValueError("Application arguments must be a list of up to 32 strings")
        result.update(target=target, args=[_text(a, "argument", 1024, empty=True) for a in args])
        cwd = value.get("cwd", "")
        _text(cwd, "working directory", 1024, empty=True)
        if cwd and not Path(cwd).is_absolute():
            raise ValueError("Working directory must be an absolute path")
        if cwd:
            result["cwd"] = cwd
    elif kind == "keyboard_shortcut":
        allowed.add("keys")
        result["keys"] = "+".join(validate_shortcut(value.get("keys")))
    elif kind == "open_url":
        allowed.add("url")
        url = _text(value.get("url"), "URL", 2048)
        try:
            parsed = urlsplit(url)
            valid = (parsed.scheme in ("https", "http") and parsed.hostname
                     and not parsed.username and not parsed.password
                     and (parsed.port is None or 1 <= parsed.port <= 65535))
        except ValueError:
            valid = False
        if not valid:
            raise ValueError("Only http/https URLs without embedded credentials are permitted")
        result["url"] = url
    elif kind == "text_snippet":
        allowed |= {"text", "approved"}
        if value.get("approved") is not True:
            raise ValueError("Text snippets must be approved in the local editor")
        result.update(text=_text(value.get("text"), "snippet", 2048), approved=True)
    if set(value) - allowed:
        raise ValueError(f"Unrecognized fields for {kind}: {', '.join(sorted(set(value) - allowed))}")
    return result


def validate_profile(value: Any) -> dict[str, Any]:
    if not isinstance(value, dict) or set(value) - {"id", "name", "category", "revision", "buttons"}:
        raise ValueError("Invalid profile object")
    profile_id = identifier(value.get("id"), "Profile ID")
    name = _text(value.get("name"), "profile name", 40)
    category = value.get("category", "custom")
    if category not in CATEGORIES:
        raise ValueError("Unsupported profile category")
    revision = value.get("revision", 1)
    if type(revision) is not int or not 1 <= revision <= 0x7FFFFFFF:
        raise ValueError("Invalid profile revision")
    buttons = value.get("buttons")
    if not isinstance(buttons, list) or not 1 <= len(buttons) <= MAX_BUTTONS:
        raise ValueError(f"Profiles require 1–{MAX_BUTTONS} buttons")
    ids: set[str] = set()
    validated: list[dict[str, Any]] = []
    for button in buttons:
        if not isinstance(button, dict) or set(button) - {"id", "label", "icon", "icon_data", "icon_image", "action", "long_press"}:
            raise ValueError("Invalid button object")
        button_id = identifier(button.get("id"), "Button ID")
        if button_id in ids:
            raise ValueError(f"Duplicate button ID: {button_id}")
        ids.add(button_id)
        icon = button.get("icon", "custom")
        if icon not in ICONS:
            raise ValueError("Choose a supported icon")
        out = {"id": button_id, "label": _text(button.get("label"), "button label", 48),
               "icon": icon, "action": validate_action(button.get("action"))}
        if "icon_data" in button:
            data = button["icon_data"]
            if not isinstance(data, str) or len(data) != 96:
                raise ValueError("Custom icons must be 24×24 packed monochrome images")
            try:
                if len(base64.b64decode(data, validate=True)) != 72:
                    raise ValueError("Custom icon data must contain 72 bytes")
            except (ValueError, base64.binascii.Error) as exc:
                raise ValueError("Invalid custom icon encoding") from exc
            out["icon_data"] = data
        if "icon_image" in button:
            from .icons import validate_icon
            if "icon_data" in button:
                raise ValueError("Choose either a color icon or a legacy monochrome icon")
            out["icon_image"] = validate_icon(button["icon_image"])
        if button.get("long_press") is not None:
            out["long_press"] = validate_action(button["long_press"])
        validated.append(out)
    return {"id": profile_id, "name": name, "category": category,
            "revision": revision, "buttons": validated}


def device_profile(profile: dict[str, Any]) -> dict[str, Any]:
    return {**{key: profile[key] for key in ("id", "name", "category", "revision")},
            "buttons": [{**{key: b[key] for key in ("id", "label", "icon")},
                         **({"icon_data": b["icon_data"]} if "icon_data" in b else {}),
                         **({"icon_asset": b["icon_image"]["id"]} if "icon_image" in b else {}),
                         "has_long_press": "long_press" in b}
                        for b in profile["buttons"]]}


class ProfileManager:
    def __init__(self, directory: Path):
        self.directory = directory / "profiles"
        self.directory.mkdir(parents=True, exist_ok=True)
        self.profiles: dict[str, dict[str, Any]] = {}
        self.errors: list[str] = []
        for path in sorted(self.directory.glob("*.json")):
            try:
                self._load(path)
            except (OSError, ValueError) as exc:
                self.errors.append(f"{path.name}: {exc}")
        if not self.profiles:
            for path in sorted((resource_directory() / "profiles").glob("*.json")):
                if path.name == "device_defaults.json":
                    continue
                self._load(path)
                atomic_json(self.directory / path.name, self.profiles[path.stem])
        if not self.profiles:
            raise ValueError("No valid profiles found; reinstall the bundled profiles")
        if len(self.profiles) > MAX_PROFILES:
            raise ValueError(f"At most {MAX_PROFILES} profiles are supported")

    def _load(self, path: Path) -> None:
        if path.stat().st_size > MAX_LOCAL_PROFILE:
            raise ValueError("Profile file is too large")
        value = validate_profile(decode_json(path.read_bytes(), max_bytes=MAX_LOCAL_PROFILE))
        if value["id"] in self.profiles:
            raise ValueError("Duplicate profile ID")
        self.profiles[value["id"]] = value

    def snapshot(self) -> dict[str, dict[str, Any]]:
        return copy.deepcopy(self.profiles)

    def save(self, profile: dict[str, Any]) -> dict[str, Any]:
        validated = validate_profile(profile)
        old = self.profiles.get(validated["id"])
        if old is None and len(self.profiles) >= MAX_PROFILES:
            raise ValueError(f"At most {MAX_PROFILES} profiles are supported")
        validated["revision"] = (old["revision"] + 1) if old else 1
        if validated["revision"] > 0x7FFFFFFF:
            raise ValueError("Profile revision limit reached; create a new profile")
        if len((json.dumps(validated, ensure_ascii=False, indent=2) + "\n").encode("utf-8")) > MAX_LOCAL_PROFILE:
            raise ValueError(f"Local profile exceeds {MAX_LOCAL_PROFILE} bytes; reduce arguments or snippets")
        prospective = {**self.profiles, validated["id"]: validated}
        self.bundle(validated["id"], profiles=prospective)
        atomic_json(self.directory / f"{validated['id']}.json", validated)
        self.profiles[validated["id"]] = validated
        return copy.deepcopy(validated)

    def delete(self, profile_id: str) -> None:
        identifier(profile_id)
        if len(self.profiles) <= 1:
            raise ValueError("Keep at least one profile")
        (self.directory / f"{profile_id}.json").unlink(missing_ok=True)
        self.profiles.pop(profile_id, None)

    def bundle(self, active: str, sequence: int = 1, session: str = "0" * 32,
               profiles: dict[str, dict[str, Any]] | None = None) -> dict[str, Any]:
        profiles = self.profiles if profiles is None else profiles
        if active not in profiles:
            active = next(iter(profiles))
        value = {"type": "profile_sync", "schema": 1, "sequence": sequence,
                 "session": session, "active": active,
                 "profiles": [device_profile(p) for p in profiles.values()]}
        try:
            encode_json(value)
        except ProtocolError as exc:
            raise ValueError(f"Device layouts exceed {MAX_MESSAGE} bytes; reduce buttons/custom icons") from exc
        return value

    @staticmethod
    def find_action(profiles: dict[str, dict[str, Any]], profile_id: str,
                    button_id: str, gesture: str) -> dict[str, Any]:
        identifier(profile_id, "Profile ID")
        identifier(button_id, "Button ID")
        if gesture not in ("press", "long"):
            raise ValueError("Unsupported gesture")
        profile = profiles.get(profile_id)
        if profile is None:
            raise ValueError("Unknown profile; synchronize it first")
        button = next((b for b in profile["buttons"] if b["id"] == button_id), None)
        if button is None:
            raise ValueError("Unknown button")
        action = button.get("long_press" if gesture == "long" else "action")
        if action is None:
            raise ValueError("No long-press action is assigned")
        return action

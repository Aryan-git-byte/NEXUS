"""Generate compact, antialiased LVGL 9 fonts from OFL-licensed Montserrat Bold.

The generated C is committed; firmware builds never need a font converter.
Only clock characters are included in the large fonts. All font data is const
flash storage. Pillow is already a companion development dependency.
"""
from __future__ import annotations

from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / "assets/fonts/Montserrat-Bold.ttf"
DESTINATION = ROOT / "firmware/main/assets"


def generate(name: str, size: int, characters: str, tabular: bool = False) -> str:
    font = ImageFont.truetype(str(FONT), size)
    ascent, descent = font.getmetrics()
    cell = max(round(font.getlength(digit)) for digit in "0123456789")
    bitmap = bytearray()
    glyphs = ["    {0}"]
    for char in characters:
        left, top, right, bottom = font.getbbox(char, anchor="ls")
        width, height = right - left, bottom - top
        advance = cell if tabular and char != ":" else round(font.getlength(char))
        offset_x = left + (advance - round(font.getlength(char))) // 2
        index = len(bitmap)
        if width and height:
            image = Image.new("L", (width, height))
            ImageDraw.Draw(image).text((-left, -top), char, font=font, fill=255, anchor="ls")
            pixels = [(value * 15 + 127) // 255 for value in image.tobytes()]
            if len(pixels) % 2:
                pixels.append(0)
            bitmap.extend((pixels[i] << 4) | pixels[i + 1] for i in range(0, len(pixels), 2))
        glyphs.append(f"    {{.bitmap_index = {index}, .adv_w = {advance * 16}, .box_w = {width}, "
                      f".box_h = {height}, .ofs_x = {offset_x}, .ofs_y = {-bottom}}}")
    start = ord(characters[0])
    offsets = [ord(char) - start for char in characters]
    contiguous = offsets == list(range(len(characters)))
    cmap_type = "LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY" if contiguous else "LV_FONT_FMT_TXT_CMAP_SPARSE_TINY"
    lines = [f"static const uint8_t {name}_pixels[] = {{"]
    lines.extend("    " + ", ".join(f"0x{byte:02x}" for byte in bitmap[i:i + 20]) + ","
                 for i in range(0, len(bitmap), 20))
    lines.extend(["};", f"static const lv_font_fmt_txt_glyph_dsc_t {name}_glyphs[] = {{",
                  ",\n".join(glyphs), "};"])
    if not contiguous:
        lines.append(f"static const uint16_t {name}_characters[] = {{{', '.join(map(str, offsets))}}};")
    lines.extend([
        f"static const lv_font_fmt_txt_cmap_t {name}_cmap[] = {{{{",
        f"    .range_start = {start}, .range_length = {offsets[-1] + 1}, .glyph_id_start = 1,",
        f"    .unicode_list = {'NULL' if contiguous else name + '_characters'}, .glyph_id_ofs_list = NULL,",
        f"    .list_length = {0 if contiguous else len(offsets)}, .type = {cmap_type}",
        "}};",
        f"static const lv_font_fmt_txt_dsc_t {name}_data = {{",
        f"    .glyph_bitmap = {name}_pixels, .glyph_dsc = {name}_glyphs, .cmaps = {name}_cmap,",
        "    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4, .kern_classes = 0, .bitmap_format = 0",
        "};",
        f"const lv_font_t {name} = {{",
        "    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt, .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,",
        f"    .line_height = {ascent + descent}, .base_line = {descent}, .subpx = LV_FONT_SUBPX_NONE,",
        f"    .underline_position = -2, .underline_thickness = 1, .dsc = &{name}_data,",
        "    .fallback = &lv_font_montserrat_20",
        "};", ""
    ])
    print(f"{name}: {len(characters)} glyphs, {len(bitmap):,} bitmap bytes, {ascent + descent}px line height")
    return "\n".join(lines)


def main() -> None:
    if not FONT.is_file():
        raise SystemExit(f"Missing licensed font: {FONT}")
    fonts = [("nexus_clock_80", 80, "-0123456789:", True),
             ("nexus_clock_112", 112, "-0123456789:", True),
             ("nexus_bold_22", 22, "".join(chr(code) for code in range(32, 127)), False)]
    DESTINATION.mkdir(parents=True, exist_ok=True)
    source = ["// Generated by tools/build_clock_fonts.py. Montserrat Bold: SIL OFL 1.1.",
              '// See assets/fonts/OFL.txt for the original font license.',
              '#include "clock_fonts.h"', '#include "lvgl.h"', ""]
    source.extend(generate(*entry) for entry in fonts)
    (DESTINATION / "clock_fonts.c").write_text("\n".join(source), "utf-8", newline="\n")
    declarations = "\n".join(f"extern const lv_font_t {name};" for name, *_ in fonts)
    (DESTINATION / "clock_fonts.h").write_text(
        '#pragma once\n#include "lvgl.h"\n#ifdef __cplusplus\nextern "C" {\n#endif\n'
        + declarations + '\n#ifdef __cplusplus\n}\n#endif\n', "utf-8", newline="\n")


if __name__ == "__main__":
    main()
